/** A transfer curve: input 0…1 (along the effect) → output 0…1, points sorted by x. */
export interface Contour {
  readonly preset: ContourPreset;
  readonly points: readonly ContourPoint[];
}

export const MAX_CONTOUR_POINTS = 16;

export const contourPreset = (preset: Exclude<ContourPreset, "custom">): Contour => ({
  preset,
  points: CONTOUR_PRESETS[preset],
});

export const LINEAR_CONTOUR: Contour = contourPreset("linear");

/** Value of a contour at t (0…1), piecewise linear. */
export function evaluateContour(contour: Contour, t: number): number {
  const pts = contour.points;
  const x = Math.min(1, Math.max(0, t));
  if (x <= pts[0].x) return pts[0].y;
  for (let i = 1; i < pts.length; i++) {
    const a = pts[i - 1];
    const b = pts[i];
    if (x <= b.x) return b.x === a.x ? b.y : a.y + ((x - a.x) / (b.x - a.x)) * (b.y - a.y);
  }
  return pts[pts.length - 1].y;
}

