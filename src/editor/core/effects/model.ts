/** The copies of one kind (empty when there are none). */
export function effectList<K extends EffectKind>(
  effects: LayerEffects | undefined,
  kind: K,
): readonly EffectByKind[K][] {
  return (effects?.[kind] ?? []) as readonly EffectByKind[K][];
}

export function firstEffect<K extends EffectKind>(
  effects: LayerEffects | undefined,
  kind: K,
): EffectByKind[K] | undefined {
  return effectList(effects, kind)[0];
}

export function hasActiveEffects(effects: LayerEffects | undefined): boolean {
  if (!effects) return false;
  return EFFECT_KINDS.some((kind) => effectList(effects, kind).some((e) => e.enabled));
}

/** The angle an effect uses: its own, or the document's global light. */
export function effectAngle(
  effect: { readonly angle: number; readonly useGlobalLight: boolean },
  light: GlobalLight | undefined,
): number {
  return effect.useGlobalLight ? (light ?? DEFAULT_GLOBAL_LIGHT).angle : effect.angle;
}

const isRecord = (v: unknown): v is Record<string, unknown> =>
  typeof v === "object" && v !== null && !Array.isArray(v);

/**
 * Effects saved before schema v7 (one object per kind, fewer settings) in the new shape, with
 * the new settings chosen so they look exactly as they did. Unknown input is returned as is for
 * the validator to judge.
 */
export function upgradeLegacyEffects(value: unknown): unknown {
  if (!isRecord(value)) return value;
  const out: Record<string, unknown> = {};
  for (const [kind, raw] of Object.entries(value)) {
    if (Array.isArray(raw) || !isRecord(raw)) {
      out[kind] = raw;
      continue;
    }
    const e = raw;
    const base = { enabled: e.enabled, opacity: e.opacity, blendMode: "normal" };
    switch (kind) {
      case "dropShadow":
        out[kind] = [
          {
            ...base,
            color: e.color,
            angle: e.angle,
            useGlobalLight: false,
            distance: e.distance,
            spread: 0,
            size: e.blur,
            noise: 0,
            contour: LINEAR_CONTOUR,
            antiAlias: false,
            knockout: false,
          },
        ];
        break;
      case "innerShadow":
        out[kind] = [
          {
            ...base,
            color: e.color,
            angle: e.angle,
            useGlobalLight: false,
            distance: e.distance,
            choke: 0,
            size: e.blur,
            noise: 0,
            contour: LINEAR_CONTOUR,
            antiAlias: false,
          },
        ];
        break;
      case "outerGlow":
        out[kind] = [
          {
            ...base,
            fill: { kind: "color", color: e.color },
            noise: 0,
            technique: "softer",
            spread: 0,
            size: e.size,
            contour: LINEAR_CONTOUR,
            antiAlias: false,
            range: 0.5,
            jitter: 0,
          },
        ];
        break;
      case "stroke":
        out[kind] = [
          {
            ...base,
            size: e.size,
            position: "outside",
            fill: { kind: "color", color: e.color },
            overprint: false,
          },
        ];
        break;
      case "colorOverlay":
        out[kind] = [{ ...base, color: e.color }];
        break;
      case "gradientOverlay":
        out[kind] = [
          {
            ...base,
            stops: e.stops,
            reverse: e.reverse,
            style: "linear",
            method: "classic",
            align: true,
            angle: e.angle,
            scale: 1,
            offsetX: 0,
            offsetY: 0,
            dither: false,
          },
        ];
        break;
      case "bevel":
        out[kind] = [
          {
            ...DEFAULT_EFFECTS.bevel,
            enabled: e.enabled,
            highlightColor: e.color,
            highlightOpacity: e.opacity,
            shadowColor: e.shadowColor,
            shadowOpacity: e.shadowOpacity,
            angle: e.angle,
            useGlobalLight: false,
            size: e.size,
            direction: e.direction,
          },
        ];
        break;
      default:
        out[kind] = raw;
    }
  }
  return out;
}

/** How far a layer's effects reach beyond its content, in document pixels. */
export function effectReach(effects: LayerEffects | undefined): number {
  let reach = 0;
  for (const e of effectList(effects, "dropShadow")) {
    if (e.enabled) reach = Math.max(reach, e.distance + e.size * 2);
  }
  for (const e of effectList(effects, "outerGlow"))
    if (e.enabled) reach = Math.max(reach, e.size * 2);
  for (const e of effectList(effects, "stroke")) {
    if (e.enabled && e.position !== "inside") reach = Math.max(reach, e.size);
  }
  for (const e of effectList(effects, "bevel")) {
    if (e.enabled && e.style !== "inner") reach = Math.max(reach, e.size + e.soften);
  }
  return reach > 0 ? Math.ceil(reach) + 2 : 0;
}
