interface EffectBase {
  readonly enabled: boolean;
  readonly blendMode: BlendMode;
  /** 0…1 */
  readonly opacity: number;
}

/** Glows are filled with one colour or a gradient that runs from the edge outwards. */
export type GlowFill =
  | { readonly kind: "color"; readonly color: string }
  | {
      readonly kind: "gradient";
      readonly stops: readonly GradientStop[];
      readonly reverse: boolean;
    };

export type GradientStyle = "linear" | "radial" | "angle" | "reflected" | "diamond";
export type GradientMethod = "classic" | "perceptual" | "linear";

export interface DropShadowEffect extends EffectBase {
  readonly color: string;
  /** Degrees; the light comes from this direction, the shadow falls opposite. */
  readonly angle: number;
  readonly useGlobalLight: boolean;
  readonly distance: number;
  /** 0…1 of `size` that is solid before the blur starts. */
  readonly spread: number;
  /** Blur size in px. */
  readonly size: number;
  /** 0…1 */
  readonly noise: number;
  readonly contour: Contour;
  readonly antiAlias: boolean;
  /** Hide the shadow under the layer's shape (shows with a low Fill). */
  readonly knockout: boolean;
}

export interface InnerShadowEffect extends EffectBase {
  readonly color: string;
  readonly angle: number;
  readonly useGlobalLight: boolean;
  readonly distance: number;
  /** 0…1 of `size` that is solid before the blur starts. */
  readonly choke: number;
  readonly size: number;
  readonly noise: number;
  readonly contour: Contour;
  readonly antiAlias: boolean;
}

export interface OuterGlowEffect extends EffectBase {
  readonly fill: GlowFill;
  readonly noise: number;
  readonly technique: "softer" | "precise";
  readonly spread: number;
  readonly size: number;
  readonly contour: Contour;
  readonly antiAlias: boolean;
  /** 0.01…1: the part of the glow the contour spans. */
  readonly range: number;
  /** 0…1: random variation of the gradient's colours. */
  readonly jitter: number;
}

export interface InnerGlowEffect extends EffectBase {
  readonly fill: GlowFill;
  readonly noise: number;
  readonly technique: "softer" | "precise";
  /** Glow from the edges inwards, or from the centre outwards. */
  readonly source: "edge" | "center";
  readonly choke: number;
  readonly size: number;
  readonly contour: Contour;
  readonly antiAlias: boolean;
  readonly range: number;
  readonly jitter: number;
}

export interface SatinEffect extends EffectBase {
  readonly color: string;
  readonly angle: number;
  readonly distance: number;
  readonly size: number;
  readonly contour: Contour;
  readonly antiAlias: boolean;
  readonly invert: boolean;
}

export interface ColorOverlayEffect extends EffectBase {
  readonly color: string;
}

export interface GradientOverlayEffect extends EffectBase {
  readonly stops: readonly GradientStop[];
  readonly reverse: boolean;
  readonly style: GradientStyle;
  readonly method: GradientMethod;
  /** Use the layer's box (true) or the canvas. */
  readonly align: boolean;
  readonly angle: number;
  /** 0.1…1.5 */
  readonly scale: number;
  /** Offset as a fraction of the box, −1.5…1.5. */
  readonly offsetX: number;
  readonly offsetY: number;
  readonly dither: boolean;
}

export interface PatternOverlayEffect extends EffectBase {
  readonly pattern: PatternId;
  readonly angle: number;
  /** 0.01…10 */
  readonly scale: number;
  readonly align: boolean;
  /** px */
  readonly offsetX: number;
  readonly offsetY: number;
}

export type StrokeFill =
  | { readonly kind: "color"; readonly color: string }
  | {
      readonly kind: "gradient";
      readonly stops: readonly GradientStop[];
      readonly reverse: boolean;
      readonly style: GradientStyle;
      readonly angle: number;
      readonly scale: number;
    };

export interface StrokeEffect extends EffectBase {
  readonly size: number;
  readonly position: "outside" | "inside" | "center";
  readonly fill: StrokeFill;
  /** Blend the stroke with the layer instead of covering it. */
  readonly overprint: boolean;
}

export type BevelStyle = "inner" | "outer" | "emboss" | "pillow" | "stroke";
export type BevelTechnique = "smooth" | "chisel-hard" | "chisel-soft";

export interface BevelContour {
  readonly enabled: boolean;
  readonly contour: Contour;
  readonly antiAlias: boolean;
  /** 0.01…1 */
  readonly range: number;
}

export interface BevelTexture {
  readonly enabled: boolean;
  readonly pattern: PatternId;
  /** 0.01…10 */
  readonly scale: number;
  /** −10…10 (−1000%…1000%) */
  readonly depth: number;
  readonly invert: boolean;
  readonly align: boolean;
  readonly offsetX: number;
  readonly offsetY: number;
}

/** Bevel & Emboss has its own highlight and shadow blending instead of one blend mode. */
export interface BevelEffect {
  readonly enabled: boolean;
  readonly style: BevelStyle;
  readonly technique: BevelTechnique;
  /** 0.01…10 (1%…1000%) */
  readonly depth: number;
  readonly direction: "up" | "down";
  readonly size: number;
  readonly soften: number;
  readonly angle: number;
  /** Degrees above the horizon, 0…90. */
  readonly altitude: number;
  readonly useGlobalLight: boolean;
  readonly glossContour: Contour;
  readonly glossAntiAlias: boolean;
  readonly highlightMode: BlendMode;
  readonly highlightColor: string;
  readonly highlightOpacity: number;
  readonly shadowMode: BlendMode;
  readonly shadowColor: string;
  readonly shadowOpacity: number;
  readonly contour: BevelContour;
  readonly texture: BevelTexture;
}

export interface EffectByKind {
  readonly dropShadow: DropShadowEffect;
  readonly innerShadow: InnerShadowEffect;
  readonly outerGlow: OuterGlowEffect;
  readonly innerGlow: InnerGlowEffect;
  readonly bevel: BevelEffect;
  readonly satin: SatinEffect;
  readonly colorOverlay: ColorOverlayEffect;
  readonly gradientOverlay: GradientOverlayEffect;
  readonly patternOverlay: PatternOverlayEffect;
  readonly stroke: StrokeEffect;
}

