// Copies Picstea's curated Google Fonts from the @fontsource packages into public/fonts and writes
// the manifest src/editor/fonts/bundled-fonts.ts (ADR-0040). Only the "latin" subset (which covers
// Western European accents) at weights 400 and 700, upright and italic where the family has them.
// Run after changing the list or the @fontsource versions: `node scripts/copy-fonts.mjs`.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** Package id → the family's place in the picker. */
const FONTS = {
  roboto: "sans-serif",
  "open-sans": "sans-serif",
  lato: "sans-serif",
  montserrat: "sans-serif",
  poppins: "sans-serif",
  inter: "sans-serif",
  raleway: "sans-serif",
  nunito: "sans-serif",
  "work-sans": "sans-serif",
  "source-sans-3": "sans-serif",
  oswald: "sans-serif",
  "bebas-neue": "display",
  merriweather: "serif",
  "playfair-display": "serif",
  lora: "serif",
  "pt-serif": "serif",
  "libre-baskerville": "serif",
  "eb-garamond": "serif",
  anton: "display",
  "abril-fatface": "display",
  lobster: "handwriting",
  pacifico: "handwriting",
  "dancing-script": "handwriting",
  caveat: "handwriting",
  "indie-flower": "handwriting",
  "roboto-mono": "monospace",
  "source-code-pro": "monospace",
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "public", "fonts");
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

const PS_STYLE = {
  "400-normal": "Regular",
  "400-italic": "Italic",
  "700-normal": "Bold",
  "700-italic": "BoldItalic",
};
const manifest = [];
const credits = [];
for (const [id, category] of Object.entries(FONTS)) {
  const pkg = join(root, "node_modules", "@fontsource", id);
  const meta = JSON.parse(readFileSync(join(pkg, "metadata.json"), "utf8"));
  const { version } = JSON.parse(readFileSync(join(pkg, "package.json"), "utf8"));
  if (!meta.license?.type?.startsWith("OFL"))
    throw new Error(`${id}: not OFL (${meta.license?.type})`);
  mkdirSync(join(target, id), { recursive: true });
  const faces = [];
  for (const weight of [400, 700]) {
    for (const style of ["normal", "italic"]) {
      const file = `${id}-latin-${weight}-${style}.woff2`;
      const from = join(pkg, "files", file);
      if (!existsSync(from)) continue;
      copyFileSync(from, join(target, id, file));
      faces.push({
        weight,
        italic: style === "italic",
        url: `/fonts/${id}/${file}`,
        postscriptName: `${meta.family.replace(/\s+/g, "")}-${PS_STYLE[`${weight}-${style}`]}`,
      });
    }
  }
  if (faces.length === 0) throw new Error(`${id}: no latin 400/700 faces`);
  copyFileSync(join(pkg, "LICENSE"), join(target, id, "OFL.txt"));
  // Compact: [family, category, package id, faces as bits (1 = 400, 2 = 400 italic, 4 = 700,
  // 8 = 700 italic)]. URLs and PostScript names are derived in font-catalog.ts.
  const bits = faces.reduce((b, f) => b | ((f.weight === 700 ? 4 : 1) << (f.italic ? 1 : 0)), 0);
  manifest.push([meta.family, category, id, bits]);
  credits.push(`${meta.family} (@fontsource/${id} ${version}): ${meta.license.attribution}`);
}
writeFileSync(
  join(target, "LICENSES.txt"),
  "Fonts bundled with Picstea. Each is licensed under the SIL Open Font License 1.1; the full\n" +
    "licence is in OFL.txt in each font's folder.\n\n" +
    credits.join("\n\n") +
    "\n",
);
writeFileSync(
  join(root, "src", "editor", "fonts", "bundled-fonts.ts"),
  "// Generated by scripts/copy-fonts.mjs — do not edit by hand.\n" +
    'import type { FontCategory } from "./font-catalog";\n\n' +
    "/** [family, category, package id, face bits: 1 = 400, 2 = 400 italic, 4 = 700, 8 = 700 italic] */\n" +
    "export const BUNDLED_FONT_DATA: readonly (readonly [string, FontCategory, string, number])[] = [\n" +
    manifest.map((m) => `  ${JSON.stringify(m)},`).join("\n") +
    "\n];\n",
);
console.log(`Copied ${manifest.length} families to ${target}`);
